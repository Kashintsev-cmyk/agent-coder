# Общее правило structured memory для всех режимов с инструментами
# (PLAN/ACT/AUDIT). Специфика режима — в его SYSTEM_*, это правило —
# инвариант: факты должны переживать сжатие истории, иначе модель
# ищет заново (подтверждено на реальных сессиях, A5/A7).
_WORK_STATE_RULE = """\
## Structured memory (правило для всех режимов)

После значимых шагов в ACT и AUDIT — нашёл причину проблемы, сделал
правку, прогнал тесты или закрыл секцию аудита — вызывай
`update_work_state`, чтобы сохранить результат в `findings`/`done`.
Иначе при сжатии истории (compress) эти факты потеряются, и ты будешь
искать заново.

В ACT объединяй факты и следующий шаг одного смыслового этапа в один вызов.
Не вызывай `update_work_state` повторно, чтобы переформулировать или
дополнить только что записанный факт; обновляй его, лишь если появились
новые сведения или изменился статус.

В AUDIT — особо жёстко; после КАЖДОГО turn: «не батчи на конец аудита».
Единое правило и порядок пачек — в `audit_standard.md`.

В PLAN — короткие исследовательские запросы не требуют записи `todo`.
Используй `update_work_state` только если нужно сохранить существенный план
незавершённой многошаговой задачи для продолжения после сжатия истории.
Не записывай каждый промежуточный вывод.

Пиши конкретику, не пересказ:
  плохо:  "работал с файлом commands.py"
  хорошо: "commands.py:399 — _create_project_on_disk не проверяет name"
  плохо:  "тесты падают"
  хорошо: "pytest: 3 failed в test_standard.py (F821 unknown name)"

Точечные операции: `{"findings+": [...]}` дописать, `{"todo": [...]}`
заменить, `{"done-": [...]}` удалить.
"""


def _with_rules(base: str, workspace: str) -> str:
    try:
        from agent_coder.agent.workspace_rules import append_rules

        base = append_rules(base, workspace)
    except Exception:
        logger.debug(
            "workspace rules: не удалось применить, работаем без них",
            exc_info=True,
        )
    try:
        from agent_coder.rules import append_command_style

        return append_command_style(base)
    except Exception:
        logger.debug("command style: не удалось применить", exc_info=True)
        return base


def system_prompt(
    mode: Mode,
    workspace: str,
    audit_scopes: list[str] | None = None,
) -> str:
    """Собрать СТАБИЛЬНЫЙ system prompt для главного агента.

    Единый принцип: PLAN/ACT/AUDIT получают _WORK_STATE_RULE (structured
    memory — инвариант, факты должны переживать compress). Специфика режима —
    в его SYSTEM_* / audit_standard.md, не здесь.

    AUDIT — без _with_rules (AGENTS.md): аудит идёт по audit_standard.md,
    это отдельное решение, не часть structured memory.

    Внутрь НЕ входят волатильные блоки [WORK_STATE] и [ПРОЧИТАННЫЕ ФАЙЛЫ]:
    они меняются почти каждую итерацию, а system — это начало запроса.
    Любая правка в нём сбивает OpenAI prefix-кэш на всём контексте.
    Их отдаёт volatile_block() и loop добавляет в хвост запроса.

    audit_scopes — B11.3: относительные пути из --scope/--scope-file.
    Только для AUDIT: встраивается блок «Область аудита» в audit_standard.
    """
    if mode == Mode.AUDIT:
        from agent_coder.agent.audit_prompt import build_audit_prompt
        from agent_coder.rules import append_command_style

        base = build_audit_prompt(workspace=workspace, scopes=audit_scopes)
        base = append_command_style(base)
    else:
        template = SYSTEM_PLAN if mode == Mode.PLAN else SYSTEM_ACT
        base = template.format(workspace=workspace)

    base = base + "\n\n" + _WORK_STATE_RULE
    if mode == Mode.AUDIT:
        return base
    return _with_rules(base, workspace)


def volatile_block(
    work_state: object | None = None,
    read_paths: dict[str, str] | None = None,
    mode: Mode | str | None = None,
) -> str:
    """Build the bounded, mode-aware volatile tail for one LLM request.

    Session state stays complete; this renderer applies the centralized
    projection and character budget in work_state.py.
    """
    from agent_coder.agent.work_state import render_prompt_context

    state = getattr(work_state, "_state", None) if work_state is not None else None
    return render_prompt_context(state, read_paths, mode=mode)
